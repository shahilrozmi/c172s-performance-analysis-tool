function runCruiseMode(aircraft)
    fprintf('\n--- POH CRUISE PERFORMANCE REFERENCE ---\n\n');

    pressureAltitude_ft = promptScalar( ...
        'Enter pressure altitude (ft, 2000 to 12000): ', 2000, 12000);
    deltaISA_C = promptScalar( ...
        'Enter ISA temperature offset (deg C, -20 to +20): ', -20, 20);
    rpm = promptScalar('Enter engine speed (RPM, 2100 to 2700): ', ...
        2100, 2700);
    weight_lb = promptScalar( ...
        'Enter aircraft weight (lb, press Enter for 2550): ', ...
        1500, aircraft.maxGrossWeight_lb, aircraft.maxGrossWeight_lb);
    fairingFlag = promptScalar( ...
        'Speed fairings installed? (1 = yes, 0 = no): ', 0, 1, 1);
    speedFairingsInstalled = logical(fairingFlag);

    try
        cruise = pohCruisePerformance( ...
            pressureAltitude_ft, rpm, deltaISA_C, weight_lb, ...
            speedFairingsInstalled);
    catch ME
        if startsWith(ME.identifier, 'pohCruise')
            fprintf('\nMODEL ENVELOPE ERROR:\n%s\n', ME.message);
            return
        end
        rethrow(ME)
    end

    atm = atmosphereAtPressureAltitude(pressureAltitude_ft, deltaISA_C);

    fprintf('\n==================================================\n');
    fprintf('POH CRUISE PERFORMANCE REFERENCE\n');
    fprintf('==================================================\n');
    displayAtmosphere(atm);
    fprintf('Engine Speed           : %.0f RPM\n', rpm);
    fprintf('POH Power Setting      : %.1f %%MCP [POH INTERPOLATION]\n', ...
        cruise.percentMCP);
    fprintf('POH True Airspeed      : %.1f KTAS [2550 lb, fairings]\n', ...
        cruise.referenceKTAS);
    fprintf('POH Fuel Flow          : %.2f US gal/h\n', ...
        cruise.fuelFlow_GPH);
    fprintf('Mixture Condition      : %s\n', cruise.mixtureCondition);
    fprintf('Selected Weight        : %.0f lb\n', weight_lb);
    if speedFairingsInstalled
        fairingText = 'installed';
    else
        fairingText = 'not installed (-2 KTAS POH correction)';
    end
    fprintf('Speed Fairings         : %s\n', fairingText);
    fprintf('2550-lb Fairing-Adj.   : %.1f KTAS\n', ...
        cruise.fairingAdjustedReferenceKTAS);
    if cruise.weightCorrectionAvailable
        fprintf('Selected-Config Speed  : %.1f KTAS\n', ...
            cruise.selectedConfigurationKTAS);
        if cruise.weightCorrectionApplied
            fprintf('Weight Speed Increment : %+.2f KTAS [POH APPROXIMATION]\n', ...
                cruise.weightCorrection_KTAS);
        end
    else
        fprintf('Selected-Config Speed  : unavailable\n');
    end
    fprintf('Weight Correction      : %s\n', cruise.weightCorrectionStatus);
    fprintf('Correction Basis       : %s\n', cruise.weightCorrectionRule);
    fprintf('Weight-Corr. Source    : %s\n', ...
        cruise.weightCorrectionSource);
    fprintf('Interpolation          : %s\n', cruise.interpolationMethod);
    fprintf('Source                 : %s [POH DATA/INTERPOLATION]\n', ...
        cruise.source);

    speedModel = getValidatedCruiseSpeedModel();
    [predictedKTAS, prediction] = predictEffectiveCruiseSpeed( ...
        pressureAltitude_ft, rpm, deltaISA_C, speedModel);
    predictionError_KTAS = predictedKTAS - cruise.referenceKTAS;
    groupedRMS_KTAS = [ ...
        speedModel.crossValidation.altitude.metrics.rmsError_KTAS, ...
        speedModel.crossValidation.temperature.metrics.rmsError_KTAS, ...
        speedModel.crossValidation.rpm.metrics.rmsError_KTAS];
    groupedMaximum_KTAS = [ ...
        speedModel.crossValidation.altitude.metrics.maximumAbsoluteError_KTAS, ...
        speedModel.crossValidation.temperature.metrics.maximumAbsoluteError_KTAS, ...
        speedModel.crossValidation.rpm.metrics.maximumAbsoluteError_KTAS];

    fprintf('\n--------------------------------------------------\n');
    fprintf('SEMI-EMPIRICAL CRUISE-SPEED PREDICTION\n');
    fprintf('Reference Condition    : 2550 lb, speed fairings installed\n');
    fprintf('Predicted True Airspeed: %.2f KTAS (%.2f m/s)\n', ...
        predictedKTAS, prediction.speed_mps);
    fprintf('POH Reference Airspeed : %.2f KTAS\n', cruise.referenceKTAS);
    fprintf('Prediction Error       : %+.2f KTAS\n', ...
        predictionError_KTAS);
    fprintf('Effective Eta          : %.4f [COMBINED CALIBRATED TERM]\n', ...
        prediction.effectiveEta);
    fprintf('Advance Ratio          : %.4f\n', prediction.advanceRatio);
    fprintf('Engine Brake Power     : %.2f kW\n', ...
        prediction.enginePower_W / 1000);
    fprintf('Power Required         : %.2f kW\n', ...
        prediction.powerRequired_W / 1000);
    fprintf('Power-Balance Residual : %+.6f kW\n', ...
        prediction.powerBalanceResidual_W / 1000);
    fprintf('Drag / CL / CD         : %.1f N / %.3f / %.4f\n', ...
        prediction.drag_N, prediction.liftCoefficient, ...
        prediction.dragCoefficient);
    if prediction.usedAdvanceRatioGuardBand
        advanceRatioStatus = ...
            '0.01 guard band used [REPORTED LOWER-CONFIDENCE EDGE RESULT]';
    else
        advanceRatioStatus = 'inside observed POH calibration range';
    end
    fprintf('Advance-Ratio Status   : %s\n', advanceRatioStatus);
    fprintf('Worst Grouped CV RMS   : %.3f KTAS (gate %.1f KTAS)\n', ...
        max(groupedRMS_KTAS), speedModel.rmsSpeedGate_KTAS);
    fprintf('Worst Held-Out Error   : %.3f KTAS (gate %.1f KTAS)\n', ...
        max(groupedMaximum_KTAS), speedModel.maximumSpeedGate_KTAS);
    fprintf('Validation Status      : %s\n', ...
        speedModel.validationStatus);
    fprintf('Classification         : %s\n', speedModel.classification);
    fprintf(['\nThe POH block remains the primary result. The prediction is ' ...
        'validated only for the 2550-lb, fairings-installed Figure 5-8 ' ...
        'reference configuration. Selected-weight and no-fairing ' ...
        'corrections above remain POH approximations and are not applied ' ...
        'to the semi-empirical model. The failed independent eta(J) proxy ' ...
        'remains available in accuracy-audit mode 4.\n']);
end

function model = getValidatedCruiseSpeedModel()
%GETVALIDATEDCRUISESPEEDMODEL Cache the validated model within MATLAB.

    persistent cachedModel
    if isempty(cachedModel)
        cachedModel = fitEffectiveCruiseSpeedModel();
    end
    if ~cachedModel.passesSpeedValidation
        error('main:CruiseSpeedModelFailedValidation', ...
            ['The semi-empirical cruise-speed model failed its validation ' ...
             'gate and cannot be shown in the interactive tool.']);
    end
    model = cachedModel;
end

function runClimbMode()
    KT_TO_MPS = 0.514444;

    fprintf('\n--- POH MAXIMUM-RATE-CLIMB REFERENCE ---\n\n');
    pressureAltitude_ft = promptScalar( ...
        'Enter pressure altitude (ft, 0 to 12000): ', 0, 12000);

    isaAtAltitude = atmosphereAtPressureAltitude(pressureAltitude_ft, 0);
    maximumOAT_C = 40;
    if pressureAltitude_ft > 10000
        maximumOAT_C = 20;
    end
    minimumDeltaISA_C = -20 - isaAtAltitude.isaTemperature_C;
    maximumDeltaISA_C = maximumOAT_C - isaAtAltitude.isaTemperature_C;

    deltaPrompt = sprintf( ...
        'Enter ISA offset (deg C, %.1f to %+.1f for POH data): ', ...
        minimumDeltaISA_C, maximumDeltaISA_C);
    deltaISA_C = promptScalar(deltaPrompt, ...
        minimumDeltaISA_C, maximumDeltaISA_C);

    climb = pohClimbPerformance(pressureAltitude_ft, deltaISA_C);

    fprintf('\n==================================================\n');
    fprintf('POH MAXIMUM-RATE-CLIMB REFERENCE\n');
    fprintf('==================================================\n');
    displayAtmosphere(climb.atmosphere);
    fprintf('Reference Weight       : %.0f lb\n', ...
        climb.referenceWeight_lb);
    fprintf('Configuration          : %s\n', climb.configuration);
    fprintf('Mixture Condition      : %s\n', climb.mixtureCondition);
    fprintf('Best-Rate Climb Speed  : %.1f KIAS\n', ...
        climb.climbSpeed_KIAS);
    fprintf('Estimated True Speed   : %.1f KTAS (%.2f m/s) [KIAS approx EAS]\n', ...
        climb.climbSpeed_TAS_mps / KT_TO_MPS, ...
        climb.climbSpeed_TAS_mps);
    fprintf('POH Rate of Climb      : %.1f ft/min (%.3f m/s)\n', ...
        climb.rateOfClimb_fpm, climb.rateOfClimb_mps);
    fprintf('Source                 : %s [POH DATA/INTERPOLATION]\n', ...
        climb.source);
    fprintf(['\nThis result is an interpolation of published POH data, ' ...
        'not an independent climb prediction.\n']);

    sweep = climbAltitudeSweep();
    climbPlotFile = plotPohClimbEnvelope(sweep, true);
    fprintf('\nSaved POH climb-envelope figure:\n  %s\n', climbPlotFile);
end

