function runTakeoffMode()
    FT_TO_M = 0.3048;

    fprintf('\n--- POH SHORT-FIELD TAKEOFF REFERENCE ---\n\n');
    weight_lb = promptScalar( ...
        'Enter aircraft weight (lb, 2200 to 2550): ', ...
        2200, 2550, 2550);
    pressureAltitude_ft = promptScalar( ...
        'Enter pressure altitude (ft, 0 to 8000): ', 0, 8000);
    oat_C = promptScalar( ...
        'Enter outside-air temperature (deg C, 0 to 40): ', 0, 40);
    windComponent_kt = promptScalar( ...
        ['Enter runway wind component (kt; + headwind, ' ...
         '- tailwind, minimum -10): '], -10, 50, 0);
    surfaceCode = promptScalar( ...
        'Runway surface (1 = paved dry, 2 = dry grass): ', 1, 2, 1);
    if surfaceCode == 1
        runwaySurface = 'paved';
    else
        runwaySurface = 'dry grass';
    end

    takeoff = pohTakeoffPerformance(weight_lb, pressureAltitude_ft, ...
        oat_C, windComponent_kt, runwaySurface);
    isa = atmosphereAtPressureAltitude(pressureAltitude_ft, 0);
    atmosphere = atmosphereAtPressureAltitude( ...
        pressureAltitude_ft, oat_C - isa.isaTemperature_C);

    fprintf('\n==================================================\n');
    fprintf('POH SHORT-FIELD TAKEOFF REFERENCE\n');
    fprintf('==================================================\n');
    displayAtmosphere(atmosphere);
    fprintf('Aircraft Weight       : %.0f lb\n', weight_lb);
    fprintf('Runway Surface        : %s\n', runwaySurface);
    fprintf('Wind Component        : %+.1f kt (+ headwind)\n', ...
        windComponent_kt);
    fprintf('Configuration         : %s\n', takeoff.configuration);
    fprintf('Mixture Condition     : %s\n', takeoff.mixtureCondition);

    fprintf('\nLINEAR POH INTERPOLATION\n');
    fprintf('Lift-Off Speed        : %.1f KIAS\n', ...
        takeoff.interpolated.liftOffSpeed_KIAS);
    fprintf('Speed at 50 ft        : %.1f KIAS\n', ...
        takeoff.interpolated.speedAt50ft_KIAS);
    fprintf('Base Ground Roll      : %.1f ft\n', ...
        takeoff.interpolated.baseGroundRoll_ft);
    fprintf('Base Over-50-ft Dist. : %.1f ft\n', ...
        takeoff.interpolated.baseTotalOver50ft_ft);
    fprintf('Wind Correction       : %+.1f %%\n', ...
        takeoff.interpolated.windCorrectionPercent);
    fprintf('Grass Addition        : %.1f ft\n', ...
        takeoff.interpolated.grassAddition_ft);
    fprintf('Corrected Ground Roll : %d ft (%.0f m) [ROUNDED UP]\n', ...
        takeoff.interpolated.roundedUpGroundRoll_ft, ...
        ceil(takeoff.interpolated.groundRoll_ft * FT_TO_M));
    fprintf('Corrected Over 50 ft  : %d ft (%.0f m) [ROUNDED UP]\n', ...
        takeoff.interpolated.roundedUpTotalOver50ft_ft, ...
        ceil(takeoff.interpolated.totalOver50ft_ft * FT_TO_M));

    fprintf('\nCONSERVATIVE NEXT-HIGHER POH GRID\n');
    fprintf('Selected Grid         : %.0f lb, %.0f ft, %.0f deg C\n', ...
        takeoff.conservativeGrid.weight_lb, ...
        takeoff.conservativeGrid.pressureAltitude_ft, ...
        takeoff.conservativeGrid.oat_C);
    fprintf('Lift-Off / 50-ft Speed: %.0f / %.0f KIAS\n', ...
        takeoff.conservative.liftOffSpeed_KIAS, ...
        takeoff.conservative.speedAt50ft_KIAS);
    fprintf('Base Ground / Over-50 : %.0f / %.0f ft\n', ...
        takeoff.conservative.baseGroundRoll_ft, ...
        takeoff.conservative.baseTotalOver50ft_ft);
    fprintf('Corrected Ground Roll : %d ft (%.0f m) [ROUNDED UP]\n', ...
        takeoff.conservative.roundedUpGroundRoll_ft, ...
        ceil(takeoff.conservative.groundRoll_ft * FT_TO_M));
    fprintf('Corrected Over 50 ft  : %d ft (%.0f m) [ROUNDED UP]\n', ...
        takeoff.conservative.roundedUpTotalOver50ft_ft, ...
        ceil(takeoff.conservative.totalOver50ft_ft * FT_TO_M));
    fprintf('Source                : %s [POH DATA/CORRECTIONS]\n', ...
        takeoff.source);
    fprintf(['\nThese are POH reference calculations, not dispatch or ' ...
        'flight-planning authorization. Apply all current POH limitations, ' ...
        'runway slope/condition effects, and operational safety margins.\n']);
end

