function data = pohLandingData()
%POHLANDINGDATA Digitized C172S POH Figure 5-11 landing data.
%
%   DATA contains short-field landing ground roll and total distance to
%   clear a 50-ft obstacle at 2550 lb. Rows correspond to pressure
%   altitude and columns to outside-air temperature.
%
%   Published conditions:
%       Flaps FULL, power idle
%       Maximum braking
%       Paved, level, dry runway
%       Zero wind
%       Speed at 50 ft: 61 KIAS
%
%   Source: C172S POH/AFM 172SPHBUS-02, Figure 5-11.

    data.source = 'C172S POH/AFM 172SPHBUS-02, Figure 5-11';
    data.referenceWeight_lb = 2550;
    data.altitudeGrid_ft = 0:1000:8000;
    data.temperatureGrid_C = 0:10:40;
    data.speedAt50ft_KIAS = 61;
    data.grassAdditionFractionOfGroundRoll = 0.45;
    data.flapsUpDistanceMultiplier = 1.35;
    data.flapsUpSpeedIncrement_KIAS = 9;
    data.maximumPublishedTailwind_kt = 10;
    data.configuration = 'Flaps FULL, power idle, maximum braking';
    data.referenceRunway = 'paved, level, dry';

    data.groundRoll_ft = [ ...
        545, 565, 585, 605, 625; ...
        565, 585, 605, 625, 650; ...
        585, 610, 630, 650, 670; ...
        610, 630, 655, 675, 695; ...
        630, 655, 675, 700, 725; ...
        655, 680, 705, 725, 750; ...
        680, 705, 730, 755, 780; ...
        705, 730, 760, 785, 810; ...
        735, 760, 790, 815, 840];

    data.totalOver50ft_ft = [ ...
        1290, 1320, 1350, 1380, 1415; ...
        1320, 1350, 1385, 1420, 1450; ...
        1355, 1385, 1420, 1455, 1490; ...
        1385, 1425, 1460, 1495, 1530; ...
        1425, 1460, 1495, 1535, 1570; ...
        1460, 1500, 1535, 1575, 1615; ...
        1500, 1540, 1580, 1620, 1660; ...
        1545, 1585, 1625, 1665, 1705; ...
        1585, 1630, 1670, 1715, 1755];
end
